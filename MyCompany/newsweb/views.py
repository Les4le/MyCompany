def render_section(request, section):
    context = {
        **SECTIONS[section],
        'current_slug': section,
        'sections': [
            {'slug': 'home', 'label': 'Новини'},
            {'slug': 'events', 'label': 'Події'},
            {'slug': 'achievements', 'label': 'Досягнення'},
            {'slug': 'articles', 'label': 'Статті'},
            {'slug': 'announcements', 'label': 'Оголошення'},
        ],
    }
    return render(request, 'newsweb/section.html', context)


def home(request):
    return render_section(request, 'home')


def events(request):
    return render_section(request, 'events')


def achievements(request):
    return render_section(request, 'achievements')


def articles(request):
    return render_section(request, 'articles')


def announcements(request):
    return render_section(request, 'announcements')
